echo " roles in existing data"
echo ""

echo "3. Updated organogram data summary:"
echo ""
jq 'length' "$UPDATED_DATA" 2>/dev/null || echo "Cannot read JSON file"
echo " roles in updated data"
echo ""

echo "4. Comparison needed:"
echo ""
echo "To properly update the organogram data, you need to:"
echo ""
echo "a) Examine the new organogram images/PDF to identify:"
echo "   • New roles added"
echo "   • Roles removed"
echo "   • Reporting structure changes"
echo "   • Grade/function updates"
echo ""
echo "b) Update the JSON data file with these changes"
echo ""
echo "c) Update PowerPoint files in Documents/IIH:"
echo "   • IIH_Organogram_PowerPoint_20260224_2349.pptx"
echo "   • IIH_TEXT_ONLY_ORGANOGRAM_20260225_0004.pptx"
echo "   • Other organogram presentation files"
