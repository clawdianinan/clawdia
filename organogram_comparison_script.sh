#!/bin/bash
# Organogram Comparison Script
# Helps compare new organogram attachments with existing data

echo "=== ORGANOGRAM COMPARISON TOOL ==="
echo ""

# Configuration
IIH_DOCS="$HOME/Documents/IIH"
NEW_ATTACHMENTS="$IIH_DOCS/Organogram_Attachments_20260227"
EXISTING_DATA="$IIH_DOCS/Organogram_Data_Backup_20260227_0549/IIH_Organogram_Data_v1_20260227_0549.json"
UPDATED_DATA="/Users/clawdia/.openclaw/workspace/IIH_Organogram_Data_v2_20260227_0940.json"

